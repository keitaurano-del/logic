// Lightweight i18n: flat key-value lookup with locale auto-detection.
// Switching locale persists to localStorage and reloads the page (simplest reactivity).

export type Locale = 'ja' | 'en'

const STORAGE_KEY = 'logic-locale'

function detectLocale(): Locale {
  try {
    const saved = localStorage.getItem(STORAGE_KEY) as Locale | null
    if (saved === 'ja' || saved === 'en') return saved
  } catch { /* */ }
  // SCRUM-216: 日本語アプリなのでデフォルトをjaに固定（ブラウザ言語に関わらず日本語に）
  return 'ja'
}

let currentLocale: Locale = detectLocale()

export function getLocale(): Locale {
  return currentLocale
}

export function setLocale(loc: Locale): void {
  try {
    localStorage.setItem(STORAGE_KEY, loc)
  } catch { /* */ }
  currentLocale = loc
  // Nuclear but reliable: full reload to re-render every component with new strings
  window.location.reload()
}

// Static HTML pages live in /public; English variants use the `-en` suffix.
export function localizedHtmlPath(slug: 'privacy' | 'terms' | 'tokushoho' | 'account-deletion' | 'delete-account'): string {
  return getLocale() === 'en' ? `/${slug}-en.html` : `/${slug}.html`
}

